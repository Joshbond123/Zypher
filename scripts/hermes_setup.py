#!/usr/bin/env python3
"""hermes_setup.py — Write Hermes config.yaml and .env from environment variables.

FULL BUG HISTORY (all issues fixed as of May 2026):

  [FIXED] PROBLEM 1 — api_key vs key_env → HTTP 401 Missing Authentication header
  [FIXED] PROBLEM 2 — missing type: openai → auth skipped in some builds
  [FIXED] PROBLEM 3 — fallback_providers missing api_key → 401 on fallbacks
  [FIXED] PROBLEM 4 — wrong primary model ID
  [FIXED] PROBLEM 5 — no context_length → compression at ~1,024 tokens every turn
  [FIXED] PROBLEM 6 — auxiliary compression provider:main not supported
  [FIXED] PROBLEM 7 — ALL models 404 (confirmed live Cerebras catalog May 2026)
  [FIXED] PROBLEM 8 — HTTP 400 reasoning_content from reasoning models
  [FIXED] PROBLEM 9 — Rate limit 429 on qwen-3-235b → max_tokens reduced to 4096
  [FIXED] PROBLEM 10 — Context compression loop at ~1,317 tokens on llama3.1-8b
  [FIXED] PROBLEM 11 — WRONG config.yaml keys (maxCharsMemory, maxCharsUser,
    autoSaveIntervalSec, directory, agent.memoryFile, agent.userMemoryFile,
    agent.workspace, agent.skillsDir, skills.autoLoad, skills.directory)
    NONE of these keys exist in Hermes v0.14. Using them silently causes Hermes
    to fall back to defaults or reject the config entirely.
    FIX: Use correct v0.14 keys: memory_char_limit, user_char_limit,
    memory_enabled, user_profile_enabled. Name is top-level. Skills/memory
    dirs are auto-discovered from HERMES_HOME (~/.hermes/).
  [FIXED] PROBLEM 12 — SOUL.md installed as AGENTS.md instead of SOUL.md
    Hermes auto-loads ~/.hermes/SOUL.md as slot #1 of the system prompt.
    No config.yaml key exists for this — it is purely file-based.
    FIX: Install AGENTS.md as ~/.hermes/SOUL.md in the workflow.

  CONFIRMED LIVE CEREBRAS MODEL CATALOG (api.cerebras.ai/public/v1/models, May 2026):
    ID                              ctx    reasoning  safe-for-hermes
    qwen-3-235b-a22b  131K   no         YES PRIMARY
    llama3.1-8b                     32K    no         NO too small (<64K required)
    gpt-oss-120b                    131K   yes        NO reasoning_content HTTP 400
    zai-glm-4.7                     131K   yes        NO reasoning_content HTTP 400
"""
import os, sys

HOME   = os.path.expanduser("~")
HD     = os.path.join(HOME, ".hermes")
MEMDIR = os.path.join(HD, "memories")
WS     = os.path.join(HD, "workspace")
SK     = os.path.join(HD, "skills")

PROXY_BASE_URL  = "http://127.0.0.1:7860/v1"
PRIMARY_MODEL   = "qwen-3-235b-a22b"
PRIMARY_CONTEXT = 131072
PROVIDER_NAME   = "cerebras-proxy"


def ensure_dirs():
    for d in [HD, MEMDIR, WS, SK]:
        os.makedirs(d, exist_ok=True)


def write_config():
    ensure_dirs()
    tok = os.environ.get("TELEGRAM_BOT_TOKEN", "")

    # CORRECT config.yaml for Hermes v0.14.
    #
    # Key corrections vs previous broken version:
    #   - name: is TOP-LEVEL (not under agent:)
    #   - memory block uses memory_char_limit / user_char_limit
    #     (NOT maxCharsMemory / maxCharsUser — those keys don't exist)
    #   - autoSaveIntervalSec removed (does not exist in v0.14)
    #   - memory.directory removed (Hermes auto-resolves ~/.hermes/memories/)
    #   - entire agent: block removed (memoryFile, userMemoryFile, workspace,
    #     skillsDir, systemPromptFile — none of these keys exist in v0.14)
    #   - entire skills: block removed (autoLoad, directory keys don't exist;
    #     skills are always auto-loaded from ~/.hermes/skills/)
    #   - SOUL.md is loaded automatically from ~/.hermes/SOUL.md — no config key
    cfg = (
        "# ~/.hermes/config.yaml — Zypher Agent (auto-generated by hermes_setup.py)\n"
        "# Hermes v0.14 — verified against official NousResearch documentation\n"
        "#\n"
        "# SOUL.md is loaded automatically from ~/.hermes/SOUL.md\n"
        "# Skills auto-loaded from ~/.hermes/skills/\n"
        "# Memories auto-loaded from ~/.hermes/memories/\n"
        "# No config keys needed for those paths — all HERMES_HOME-relative.\n"
        "\n"
        "# ── AGENT IDENTITY ──────────────────────────────────────────────────────────\n"
        "# Top-level name key (NOT under agent: block — that block does not exist in v0.14)\n"
        "name: Zypher\n"
        "\n"
        "# ── PROVIDER ────────────────────────────────────────────────────────────────\n"
        "providers:\n"
        f"  {PROVIDER_NAME}:\n"
        f"    base_url: {PROXY_BASE_URL}\n"
        "    key_env: OPENAI_API_KEY\n"
        "    type: openai\n"
        "\n"
        "# ── PRIMARY MODEL ───────────────────────────────────────────────────────────\n"
        "# qwen-3-235b-a22b: only non-reasoning >=64K model on Cerebras.\n"
        "# max_tokens capped at 4096 to reduce TPM usage (Cerebras reserves max_tokens\n"
        "# against TPM quota — 16384 exhausted 60K TPM free tier in <4 seconds).\n"
        "model:\n"
        f"  provider: {PROVIDER_NAME}\n"
        f"  default: {PRIMARY_MODEL}\n"
        "  max_tokens: 4096\n"
        f"  context_length: {PRIMARY_CONTEXT}\n"
        "  temperature: 0.7\n"
        "  streaming: true\n"
        "\n"
        "# ── COMPRESSION ─────────────────────────────────────────────────────────────\n"
        "# Disabled: qwen-3-235b has 131K context. compression.enabled: false disables\n"
        "# the agent ContextCompressor. threshold: 0.99 is belt-and-suspenders.\n"
        "compression:\n"
        "  enabled: false\n"
        "  threshold: 0.99\n"
        "\n"
        "# ── MEMORY ──────────────────────────────────────────────────────────────────\n"
        "# Correct v0.14 keys: memory_char_limit / user_char_limit\n"
        "# (maxCharsMemory / maxCharsUser / autoSaveIntervalSec / directory do NOT exist)\n"
        "# Hermes official defaults: 2200 chars memory, 1375 chars user profile\n"
        "memory:\n"
        "  memory_enabled: true\n"
        "  user_profile_enabled: true\n"
        "  memory_char_limit: 2200\n"
        "  user_char_limit: 1375\n"
        "\n"
        "# ── GATEWAY ─────────────────────────────────────────────────────────────────\n"
        "gateway:\n"
        "  platforms:\n"
        "    telegram:\n"
        "      enabled: true\n"
        f'      botToken: "{tok}"\n'
        "      dmPolicy: open\n"
        "      streamMode: block\n"
        "      pollingStallThresholdMs: 120000\n"
        "      gateway_restart_notification: true\n"
        "\n"
        "# ── TOOLS ───────────────────────────────────────────────────────────────────\n"
        "tools:\n"
        "  bash:\n"
        "    enabled: true\n"
        "    timeoutSec: 300\n"
        "  web_search:\n"
        "    provider: tavily\n"
        "    enabled: true\n"
        "  web_fetch:\n"
        "    enabled: true\n"
        "    maxChars: 60000\n"
        "  browser:\n"
        "    enabled: true\n"
        "    headless: true\n"
        "    executablePath: /usr/bin/google-chrome-stable\n"
    )
    p = os.path.join(HD, "config.yaml")
    open(p, "w").write(cfg)
    print(f"config.yaml written -> {p}")
    print(f"  name (top-level)   : Zypher")
    print(f"  provider           : {PROVIDER_NAME} (key_env: OPENAI_API_KEY, type: openai)")
    print(f"  primary            : {PRIMARY_MODEL}")
    print(f"  max_tokens         : 4096")
    print(f"  context_length     : {PRIMARY_CONTEXT:,}")
    print(f"  memory_char_limit  : 2200 (correct v0.14 key)")
    print(f"  user_char_limit    : 1375 (correct v0.14 key)")
    print(f"  SOUL.md            : auto-loaded from ~/.hermes/SOUL.md")
    print(f"  skills dir         : auto-loaded from ~/.hermes/skills/")
    print(f"  memories dir       : auto-loaded from ~/.hermes/memories/")


def write_env():
    ensure_dirs()
    tok    = os.environ.get("TELEGRAM_BOT_TOKEN", "")
    k1     = os.environ.get("CEREBRAS_API_KEY", "")
    tav    = os.environ.get("TAVILY_API_KEY", "") or os.environ.get("TAVILY_API_KEY_2", "")
    sb_url = os.environ.get("SUPABASE_URL", "")
    sb_key = os.environ.get("SUPABASE_SERVICE_KEY", "")
    gh     = os.environ.get("GITHUB_TOKEN", "")
    uid    = os.environ.get("TELEGRAM_USER_ID", "6317345496")
    env = (
        f"CEREBRAS_API_KEY={k1}\n"
        "OPENAI_API_KEY=proxy-placeholder\n"
        "OPENROUTER_API_KEY=proxy-placeholder\n"
        f"TELEGRAM_HOME_CHANNEL={uid}\n"
        "TELEGRAM_HOME_CHANNEL_NAME=Zypher Home\n"
        f"TELEGRAM_ALLOWED_USERS={uid}\n"
        f"TELEGRAM_BOT_TOKEN={tok}\n"
        f"TAVILY_API_KEY={tav}\n"
        f"SUPABASE_URL={sb_url}\n"
        f"SUPABASE_SERVICE_KEY={sb_key}\n"
        f"GITHUB_TOKEN={gh}\n"
    )
    p = os.path.join(HD, ".env")
    open(p, "w").write(env)
    os.chmod(p, 0o600)
    print("~/.hermes/.env written")
    print(f"  OPENAI_API_KEY         : proxy-placeholder")
    print(f"  TELEGRAM_HOME_CHANNEL  : {uid}")
    print(f"  TELEGRAM_ALLOWED_USERS : {uid}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "all"
    if cmd in ("write-config", "all"):
        write_config()
    if cmd in ("write-env", "all"):
        write_env()
    print("hermes_setup.py complete")

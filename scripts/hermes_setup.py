#!/usr/bin/env python3
"""Write Hermes config.yaml and .env for Groq API inference via local key-rotation proxy.

Architecture:
  Hermes -> local groq proxy (127.0.0.1:18765) -> Groq API (llama-3.3-70b-versatile)

v5 MODEL SWITCH (2026-05):
  Changed from qwen/qwen3-32b -> llama-3.3-70b-versatile.

  WHY: qwen3-32b is a THINKING model. Every response includes a reasoning chain
  stored in reasoning_content (5K-30K tokens per turn). These tokens accumulated
  in Hermes conversation history, growing the payload by 50-200 KB after just
  3-4 turns. Even with proxy truncation of `content`, `reasoning_content` passed
  through untouched in v4.

  llama-3.3-70b-versatile:
    - 131,072 token context window (same as qwen3-32b on Groq)
    - NO thinking/reasoning mode -> responses are concise and focused
    - ~400-600 tok/s on Groq -> still fast
    - Does not produce reasoning_content -> conversation history stays small
    - Well-tested on tool-use and agentic tasks

  The proxy (v5) also injects reasoning_effort="none" as a safety net in case
  the model is ever switched back to a thinking model.

Context configuration (unchanged from v4):
  - context_length: 16384 (deliberately below Groq free-tier TPM pressure)
  - Compression threshold: 0.20 -> fires early at ~3K tokens
  - Proxy also enforces an 18KB serialized request budget

Memory limits (tightened for v5):
  - memory_char_limit: 600 (was 800)
  - user_char_limit: 400 (was 600)
"""
import os
import sys

HOME = os.path.expanduser("~")
HD   = os.path.join(HOME, ".hermes")
MEMDIR = os.path.join(HD, "memories")
WS   = os.path.join(HD, "workspace")
SK   = os.path.join(HD, "skills")

PROVIDER_NAME = "local-groq"
PROXY_PORT    = os.environ.get("GROQ_PROXY_PORT", "18765")
LOCAL_BASE_URL = f"http://127.0.0.1:{PROXY_PORT}/v1"

# v5: switched from qwen/qwen3-32b (thinking) to llama-3.3-70b-versatile (no thinking)
PRIMARY_MODEL   = "llama-3.3-70b-versatile"
FALLBACK_MODEL  = "llama-3.1-8b-instant"
PRIMARY_CONTEXT = 131072
PROVIDER_TIMEOUT = 120
LOCAL_API_KEY   = "groq-proxy"


def ensure_dirs():
    for d in [HD, MEMDIR, WS, SK]:
        os.makedirs(d, exist_ok=True)


def write_config():
    ensure_dirs()
    tok = os.environ.get("TELEGRAM_BOT_TOKEN", "")

    cfg = """# ~/.hermes/config.yaml - Zypher Agent (auto-generated by hermes_setup.py v5)
# Hermes v0.15.x
#
# PRIMARY:  {primary}
# RUNTIME:  Groq API via local key-rotation proxy (groq_key_proxy.py)
# ENDPOINT: {base_url}  ->  https://api.groq.com/openai/v1
# CONTEXT:  {context} tokens (effective limit; model max is 131072)
#
# v5 CHANGE: switched from qwen/qwen3-32b (thinking model, causes 413 via
# reasoning_content bloat) to llama-3.3-70b-versatile (no thinking mode).
#
# v6 FIX: context_length raised from 16384 to 131072.
#   Hermes Agent v0.15.x requires context_length >= 64,000. Setting it to
#   16384 caused ValueError("...below the minimum 64,000 required by Hermes
#   Agent") on every Telegram message. The groq_key_proxy already enforces
#   an 18KB byte budget per Groq request — that is the real TPM guard.

name: Zypher

providers:
  {provider}:
    base_url: {base_url}
    key_env: OPENAI_API_KEY
    context_length: {context}
    request_timeout_seconds: {timeout}
    stale_timeout_seconds: {timeout}

model:
  provider: {provider}
  default: {primary}
  context_length: {context}
  temperature: 0.3
  streaming: true

# Ordered fallback chain. The fallback is intentionally a different Groq
# production model so Hermes does not fail over to the same backend/model
# that just failed. The proxy still rotates all configured GROQ_KEY_N keys.
fallback_providers:
  - provider: {provider}
    model: {fallback}
    base_url: {base_url}
    key_env: OPENAI_API_KEY

agent:
  max_turns: 200
  clarify_timeout: 30
  gateway_notify_interval: 30
  gateway_timeout: 13200
  gateway_timeout_warning: 3600
  api_max_retries: 1
  tool_use_enforcement: true

approvals:
  mode: "off"
  cron_mode: approve
  mcp_reload_confirm: false
  destructive_slash_confirm: false

compression:
  enabled: true
  threshold: 0.05
  target_ratio: 0.04
  protect_last_n: 6

memory:
  memory_enabled: true
  user_profile_enabled: true
  memory_char_limit: 400
  user_char_limit: 300

gateway:
  platforms:
    telegram:
      enabled: true
      botToken: "{tok}"
      dmPolicy: open
      streamMode: block
      gateway_restart_notification: false

tools:
  bash:
    enabled: true
    timeoutSec: 120
  web_search:
    provider: tavily
    enabled: true
  web_fetch:
    enabled: true
    maxChars: 3000
  browser:
    enabled: true
    headless: true
    executablePath: /usr/bin/google-chrome-stable
    timeoutMs: 20000
    navigationTimeoutMs: 20000
""".format(
        primary=PRIMARY_MODEL,
        fallback=FALLBACK_MODEL,
        context=PRIMARY_CONTEXT,
        provider=PROVIDER_NAME,
        base_url=LOCAL_BASE_URL,
        timeout=PROVIDER_TIMEOUT,
        tok=tok,
    )

    p = os.path.join(HD, "config.yaml")
    with open(p, "w") as fh:
        fh.write(cfg)
    print("config.yaml written -> {}".format(p))
    print("  model              : {}  (v5: non-thinking)".format(PRIMARY_MODEL))
    print("  fallback           : {}".format(FALLBACK_MODEL))
    print("  provider           : {}".format(PROVIDER_NAME))
    print("  base_url           : {}".format(LOCAL_BASE_URL))
    print("  context_length     : {:,} (model actual max; proxy enforces 18KB/request)".format(PRIMARY_CONTEXT))
    print("  compression thresh : 0.05 ({:,} tokens — fires before proxy trim)".format(int(PRIMARY_CONTEXT * 0.05)))
    print("  memory_char_limit  : 400 chars")
    print("  user_char_limit    : 300 chars")
    print("  web_fetch maxChars : 3000 chars")
    print("  request_timeout    : {}s".format(PROVIDER_TIMEOUT))


def write_env():
    ensure_dirs()
    tok    = os.environ.get("TELEGRAM_BOT_TOKEN", "")
    tav    = os.environ.get("TAVILY_API_KEY", "") or os.environ.get("TAVILY_API_KEY_2", "")
    sb_url = os.environ.get("SUPABASE_URL", "")
    sb_key = os.environ.get("SUPABASE_SERVICE_KEY", "")
    gh     = os.environ.get("GITHUB_TOKEN", "")
    uid    = os.environ.get("TELEGRAM_USER_ID", "6317345496")

    groq_keys = []
    for i in range(1, 20):
        k = os.environ.get(f"GROQ_KEY_{i}", "").strip()
        if k:
            groq_keys.append((f"GROQ_KEY_{i}", k))

    lines = [
        f"OPENAI_API_KEY={LOCAL_API_KEY}",
        f"OPENROUTER_API_KEY={LOCAL_API_KEY}",
        f"HERMES_MODEL_PROVIDER={PROVIDER_NAME}",
        f"HERMES_MODEL_NAME={PRIMARY_MODEL}",
        f"HERMES_MODEL_BASE_URL={LOCAL_BASE_URL}",
        f"TELEGRAM_HOME_CHANNEL={uid}",
        "TELEGRAM_HOME_CHANNEL_NAME=Zypher Home",
        f"TELEGRAM_ALLOWED_USERS={uid}",
        f"TELEGRAM_BOT_TOKEN={tok}",
        f"TAVILY_API_KEY={tav}",
        f"SUPABASE_URL={sb_url}",
        f"SUPABASE_SERVICE_KEY={sb_key}",
        f"GITHUB_TOKEN={gh}",
        "HERMES_YOLO_MODE=1",
        "HERMES_GATEWAY_SESSION=1",
        f"GROQ_PROXY_PORT={PROXY_PORT}",
    ]
    for key_name, key_val in groq_keys:
        lines.append(f"{key_name}={key_val}")

    env_content = "\n".join(lines) + "\n"
    p = os.path.join(HD, ".env")
    with open(p, "w") as fh:
        fh.write(env_content)
    os.chmod(p, 0o600)
    print("~/.hermes/.env written")
    print("  HERMES_MODEL_NAME={}".format(PRIMARY_MODEL))
    print("  GROQ keys embedded: {}".format(len(groq_keys)))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "all"
    if cmd in ("write-config", "all"):
        write_config()
    if cmd in ("write-env", "all"):
        write_env()
    print("hermes_setup.py v5 complete")
